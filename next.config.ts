import type { NextConfig } from "next";

// The platform preview is embedded. A real public deployment uses the explicit
// DEPLOYMENT_TARGET=public flag (configured in the Render Blueprint).
const publicDeployment = process.env.DEPLOYMENT_TARGET === "public";
const development = process.env.NODE_ENV === "development";

const securityHeaders = [
  ...(publicDeployment ? [{ key: "X-Frame-Options", value: "DENY" }] : []),
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), browsing-topics=()" },
  { key: "X-DNS-Prefetch-Control", value: "off" },
  {
    key: "Content-Security-Policy",
    value: [
      "default-src 'self'",
      `script-src 'self' 'unsafe-inline'${development ? " 'unsafe-eval'" : ""}`,
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob: https:",
      "font-src 'self' data:",
      "connect-src 'self' https://*.supabase.co",
      `frame-ancestors ${publicDeployment ? "'none'" : "*"}`,
      "base-uri 'self'",
      "form-action 'self'",
      "object-src 'none'",
    ].join("; "),
  },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  outputFileTracingIncludes: {
    "/api/deployment/guide": ["./docs/PUBLICACAO.md", "./docs/CHECKLIST_PRODUCAO.md"],
  },
  async headers() {
    return [
      { source: "/(.*)", headers: securityHeaders },
      { source: "/sw.js", headers: [{ key: "Cache-Control", value: "no-cache" }] },
      {
        source: "/api/:path*",
        headers: [{ key: "Cache-Control", value: "private, no-store" }],
      },
    ];
  },
};

export default nextConfig;
